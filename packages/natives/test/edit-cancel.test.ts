import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import {
	EditSession,
	EditStore,
	type EditPolicy,
	type EditWriteRequest,
	type EditWriteResponse,
	glob,
} from "@oh-my-pi/pi-natives";

let dir: string;

beforeEach(async () => {
	dir = await fs.mkdtemp(path.join(os.tmpdir(), "pi-natives-edit-cancel-"));
});

afterEach(async () => {
	await fs.rm(dir, { recursive: true, force: true });
});

function policy(cwd: string): EditPolicy {
	return {
		cwd,
		mode: "hashline",
		allowFuzzy: false,
		fuzzyThreshold: 0.95,
		enforceSeenLines: false,
		maxColumns: 0,
		blockAutoGenerated: false,
		planActive: false,
		urlSchemes: ["held"],
		urlAliasSchemes: [],
		planWritableRoots: [],
		homeDir: cwd,
		rawInput: false,
	};
}

type Writer = (error: Error | null, request: EditWriteRequest) => Promise<EditWriteResponse>;

/** A host writer that writes each request to disk and records the paths it began writing. */
function diskWriter(): { begun: string[]; write: Writer } {
	const begun: string[] = [];
	return {
		begun,
		write: async (_error, request) => {
			begun.push(request.path);
			await Bun.write(request.path, request.content ?? "");
			return { written: request.content ?? "" };
		},
	};
}

/** Files the session's store has a tag for, with a hashline edit replacing line 1 of each. */
async function edit(files: string[]): Promise<{ store: EditStore; input: string }> {
	const store = new EditStore();
	let input = "";
	for (const name of files) {
		const absolute = path.join(dir, name);
		await Bun.write(absolute, "old\n");
		input += `[${name}#${store.recordSnapshot(absolute, "old\n")}]\nPUT 1.=1:\n+new\n`;
	}
	return { store, input };
}

/**
 * An edit of `held://n.md`, whose host answer for that URL waits until `release()`: the
 * apply is inside the native call, waiting on the host, until then.
 */
async function heldEdit() {
	const target = path.join(dir, "n.md");
	await Bun.write(target, "old\n");
	const store = new EditStore();
	const tag = store.recordSnapshot(target, "old\n");
	const asked = Promise.withResolvers<void>();
	const released = Promise.withResolvers<void>();
	const session = new EditSession(store, policy(dir), null, async () => {
		asked.resolve();
		await released.promise;
		return { path: target, planWritable: false };
	});
	session.setArgsJson(JSON.stringify({ input: `[held://n.md#${tag}]\nPUT 1.=1:\n+new\n` }));
	session.finish();
	return { target, session, asked: asked.promise, release: () => released.resolve() };
}

describe("EditSession.apply and the call's abort signal", () => {
	test("an edit aborted while its apply waits on the host writes nothing", async () => {
		const { target, session, asked, release } = await heldEdit();
		const writer = diskWriter();
		const controller = new AbortController();
		const outcome = session.apply({ lspFlush: false, signal: controller.signal }, writer.write);
		await asked;
		controller.abort();
		release();
		const result = await outcome;

		// The file first, so a failure shows whether the aborted apply wrote.
		expect(await Bun.file(target).text()).toBe("old\n");
		expect(writer.begun).toEqual([]);
		expect(result.isError).toBe(true);
		expect(result.errorKind).toBe("cancelled");
		expect(result.text).toBe("Edit cancelled before it wrote anything; no file was changed.");
	});

	test("an abort reaches the apply after the same signal went to another native call", async () => {
		const { target, session, asked, release } = await heldEdit();
		const writer = diskWriter();
		const controller = new AbortController();
		const outcome = session.apply({ lspFlush: false, signal: controller.signal }, writer.write);
		await asked;
		// The glob converts the same signal after the edit did; the edit must still hear the abort.
		await glob({ pattern: "*.md", path: dir, signal: controller.signal });
		controller.abort();
		release();
		const result = await outcome;

		expect(await Bun.file(target).text()).toBe("old\n");
		expect(writer.begun).toEqual([]);
		expect(result.errorKind).toBe("cancelled");
	});

	test("the same edit, not aborted, writes", async () => {
		const { target, session, asked, release } = await heldEdit();
		const writer = diskWriter();
		const controller = new AbortController();
		const outcome = session.apply({ lspFlush: false, signal: controller.signal }, writer.write);
		await asked;
		release();
		const result = await outcome;

		expect(result.isError).toBe(false);
		expect(writer.begun).toEqual([target]);
		expect(await Bun.file(target).text()).toBe("new\n");
	});

	test("an abort during the first file's write leaves the second file as it was", async () => {
		const { store, input } = await edit(["a.md", "b.md"]);
		const session = new EditSession(store, policy(dir), null, null);
		session.setArgsJson(JSON.stringify({ input }));
		session.finish();
		const controller = new AbortController();
		const writer = diskWriter();
		const result = await session.apply({ lspFlush: false, signal: controller.signal }, async (error, request) => {
			const response = await writer.write(error, request);
			controller.abort();
			return response;
		});

		expect(await Bun.file(path.join(dir, "b.md")).text()).toBe("old\n");
		expect(writer.begun).toEqual([path.join(dir, "a.md")]);
		expect(await Bun.file(path.join(dir, "a.md")).text()).toBe("new\n");
		expect(result.errorKind).toBe("cancelled");
		expect(result.text).toBe("Edit cancelled after changing a.md; no other file was changed.");
	});

	test("a host that declines a write because the call was cancelled is reported as cancelled", async () => {
		const { store, input } = await edit(["a.md"]);
		const session = new EditSession(store, policy(dir), null, null);
		session.setArgsJson(JSON.stringify({ input }));
		session.finish();
		const result = await session.apply({ lspFlush: false }, async () => ({ written: "", cancelled: true }));

		expect(result.isError).toBe(true);
		expect(result.errorKind).toBe("cancelled");
		expect(result.text).toBe("Edit cancelled before it wrote anything; no file was changed.");
		expect(await Bun.file(path.join(dir, "a.md")).text()).toBe("old\n");
	});
});
